"""Create synthetic evidence only. Run from repository root."""
import json
from pathlib import Path

cohorts = []
for year in range(2017, 2025):
    rows = []
    for i, symbol in enumerate(('SYN_A', 'SYN_B', 'SYN_DELIST', 'SYN_BLOCKED')):
        rows.append(dict(symbol=symbol, feature_period_end=f'{year-1}-12-01',
            feature_available=f'{year-1}-12-20', feature_source='synthetic fixture v1',
            outcome_source='synthetic fixture v1', momentum=(i-1)*.1 + (year % 3)*.01,
            entry_date=f'{year}-01-03', exit_date=f'{year+1}-01-04',
            label_available=f'{year+1}-01-05', entry_price=25., exit_price=0. if i==2 else 26.+(year%3),
            dividend_per_share=0.5, entry_status='limit_up' if i==1 and year%2 else 'filled',
            exit_status='delisted' if i==2 else 'blocked' if i==3 else 'filled',
            settlement_verified=True))
    cohorts.append(dict(decision=f'{year}-01-02', universe_available=f'{year-1}-12-31',
        universe_source='synthetic historical membership including later delisting', includes_delisted=True, rows=rows))
Path('alphamax/examples').mkdir(exist_ok=True)
Path('alphamax/examples/synthetic.json').write_text(json.dumps(dict(kind='synthetic',
    source='generated by alphamax/demo.py; NOT market observations',
    unverified=['Synthetic demonstration only; no investment performance established'], cohorts=cohorts), indent=2)+'\n')
